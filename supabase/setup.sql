-- 3. RPC transaccional para programar visitas.
-- Se toma un advisory lock por técnico: dos peticiones simultáneas del mismo técnico
-- se validan en serie y no pueden superar la comprobación a la vez.
create or replace function public.create_visit(
  p_technician_id integer,
  p_work_id integer,
  p_visit_date date,
  p_start_time time without time zone,
  p_duration_minutes integer
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_start_minute integer;
  v_end_minute integer;
  v_end_time time without time zone;
  v_conflict_id bigint;
  v_conflict_start time without time zone;
  v_conflict_end time without time zone;
  v_visit_id bigint;
begin
  if p_technician_id is null or p_work_id is null or p_visit_date is null
     or p_start_time is null or p_duration_minutes is null then
    return pg_catalog.jsonb_build_object(
      'success', false,
      'code', 'MISSING_FIELDS',
      'message', 'Completa todos los campos de la visita.'
    );
  end if;

  if p_duration_minutes < 15 or p_duration_minutes > 540 or p_duration_minutes % 15 <> 0 then
    return pg_catalog.jsonb_build_object(
      'success', false,
      'code', 'INVALID_DURATION',
      'message', 'La duración debe estar entre 15 y 540 minutos y ser múltiplo de 15.'
    );
  end if;

  if extract(second from p_start_time) <> 0 then
    return pg_catalog.jsonb_build_object(
      'success', false,
      'code', 'INVALID_START_TIME',
      'message', 'La hora de inicio debe tener precisión de minutos.'
    );
  end if;

  if not exists (select 1 from public.technicians t where t.id = p_technician_id) then
    return pg_catalog.jsonb_build_object(
      'success', false,
      'code', 'TECHNICIAN_NOT_FOUND',
      'message', 'El técnico seleccionado no existe.'
    );
  end if;

  if not exists (select 1 from public.works w where w.id = p_work_id) then
    return pg_catalog.jsonb_build_object(
      'success', false,
      'code', 'WORK_NOT_FOUND',
      'message', 'La obra seleccionada no existe.'
    );
  end if;

  v_start_minute := floor(extract(epoch from p_start_time) / 60)::integer;
  v_end_minute := v_start_minute + p_duration_minutes;

  if v_start_minute < 8 * 60 or v_end_minute > 17 * 60 then
    return pg_catalog.jsonb_build_object(
      'success', false,
      'code', 'OUTSIDE_WORKING_HOURS',
      'message', 'La visita debe empezar y terminar dentro de la jornada de 08:00 a 17:00.'
    );
  end if;

  v_end_time := (time '00:00' + pg_catalog.make_interval(mins => v_end_minute));

  -- Serializa cualquier alta/cancelación para el mismo técnico.
  perform pg_catalog.pg_advisory_xact_lock(78645, p_technician_id);

  -- Regla A: no se permite ningún solapamiento, tampoco en la misma obra.
  select v.id, v.start_time, v.end_time
    into v_conflict_id, v_conflict_start, v_conflict_end
  from public.visits v
  where v.technician_id = p_technician_id
    and v.visit_date = p_visit_date
    and v.status = 'scheduled'
    and v.start_time < v_end_time
    and v.end_time > p_start_time
  order by v.start_time
  limit 1;

  if found then
    return pg_catalog.jsonb_build_object(
      'success', false,
      'code', 'OVERLAP',
      'message', pg_catalog.format(
        'El técnico ya tiene una visita que se solapa (%s–%s).',
        pg_catalog.left(v_conflict_start::text, 5),
        pg_catalog.left(v_conflict_end::text, 5)
      ),
      'conflict_visit_id', v_conflict_id
    );
  end if;

  -- Regla B: comprueba las dos direcciones (visita nueva antes o después de otra).
  -- Solo aplica cuando la obra es diferente; una cancelada no bloquea.
  select v.id, v.start_time, v.end_time
    into v_conflict_id, v_conflict_start, v_conflict_end
  from public.visits v
  where v.technician_id = p_technician_id
    and v.visit_date = p_visit_date
    and v.status = 'scheduled'
    and v.work_id <> p_work_id
    and (
      (v.end_time <= p_start_time and p_start_time - v.end_time < interval '30 minutes')
      or
      (v.start_time >= v_end_time and v.start_time - v_end_time < interval '30 minutes')
    )
  order by v.start_time
  limit 1;

  if found then
    return pg_catalog.jsonb_build_object(
      'success', false,
      'code', 'TRAVEL_GAP',
      'message', pg_catalog.format(
        'Se necesitan 30 minutos entre obras distintas. La visita cercana es %s–%s.',
        pg_catalog.left(v_conflict_start::text, 5),
        pg_catalog.left(v_conflict_end::text, 5)
      ),
      'conflict_visit_id', v_conflict_id
    );
  end if;

  insert into public.visits (
    technician_id, work_id, visit_date, start_time, duration_minutes, status
  ) values (
    p_technician_id, p_work_id, p_visit_date, p_start_time, p_duration_minutes, 'scheduled'
  ) returning id into v_visit_id;

  return pg_catalog.jsonb_build_object(
    'success', true,
    'visit_id', v_visit_id,
    'message', 'Visita programada correctamente.'
  );
end;
$$;

-- 4. RPC de cancelación: conserva la fila y libera el horario al cambiar el estado.
create or replace function public.cancel_visit(p_visit_id bigint)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_technician_id integer;
  v_status text;
begin
  if p_visit_id is null then
    return pg_catalog.jsonb_build_object(
      'success', false,
      'code', 'MISSING_VISIT_ID',
      'message', 'No se ha indicado qué visita cancelar.'
    );
  end if;

  select v.technician_id
    into v_technician_id
  from public.visits v
  where v.id = p_visit_id;

  if not found then
    return pg_catalog.jsonb_build_object(
      'success', false,
      'code', 'VISIT_NOT_FOUND',
      'message', 'La visita que intentas cancelar no existe.'
    );
  end if;

  perform pg_catalog.pg_advisory_xact_lock(78645, v_technician_id);

  select v.status
    into v_status
  from public.visits v
  where v.id = p_visit_id
  for update;

  if not found then
    return pg_catalog.jsonb_build_object(
      'success', false,
      'code', 'VISIT_NOT_FOUND',
      'message', 'La visita que intentas cancelar no existe.'
    );
  end if;

  if v_status = 'cancelled' then
    return pg_catalog.jsonb_build_object(
      'success', false,
      'code', 'ALREADY_CANCELLED',
      'message', 'Esta visita ya estaba cancelada.'
    );
  end if;

  update public.visits
  set status = 'cancelled'
  where id = p_visit_id;

  return pg_catalog.jsonb_build_object(
    'success', true,
    'visit_id', p_visit_id,
    'message', 'Visita cancelada correctamente.'
  );
end;
$$;

