-- 1. Tablas
create table if not exists public.technicians (
  id integer generated by default as identity primary key,
  name text not null,
  specialty text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.works (
  id integer generated by default as identity primary key,
  name text not null,
  municipality text not null,
  address text,
  created_at timestamptz not null default now()
);

create table if not exists public.visits (
  id bigint generated by default as identity primary key,
  technician_id integer not null references public.technicians(id) on delete restrict,
  work_id integer not null references public.works(id) on delete restrict,
  visit_date date not null,
  start_time time without time zone not null,
  duration_minutes integer not null check (duration_minutes between 15 and 540 and duration_minutes % 15 = 0),
  end_time time without time zone generated always as (
    (start_time + (duration_minutes * interval '1 minute'))::time
  ) stored,
  status text not null default 'scheduled' check (status in ('scheduled', 'cancelled')),
  created_at timestamptz not null default now(),
  constraint visits_end_after_start check (end_time > start_time),
  constraint visits_inside_workday check (start_time >= time '08:00' and end_time <= time '17:00')
);

create index if not exists visits_technician_date_status_idx
  on public.visits (technician_id, visit_date, status);

create index if not exists visits_date_start_idx
  on public.visits (visit_date, start_time);

